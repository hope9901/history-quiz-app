# 기존 summaryNote 에 저장돼 있는 OCR 키워드 추출 패턴 (구버전·신버전 포맷 모두 지원)
KEYWORD_PATTERNS = [
    re.compile(r"감지된 핵심 키워드:\s*(.*?)\s*—"),   # 구버전 포맷
    re.compile(r"감지된 키워드:\s*(.*?)\s*·"),        # 신버전 포맷 (재실행 시)
]


def extract_keywords(summary_note: str) -> str:
    for pat in KEYWORD_PATTERNS:
        m = pat.search(summary_note)
        if m:
            return m.group(1).strip()
    return ""


